# ---------------------------------------------------------------------------
# Βοηθητικά για ημερομηνία λήξης (ISO string με timezone, από isoformat())
# ---------------------------------------------------------------------------

def demo_expired(expires_at_iso: str) -> bool:
    """True αν το demo έχει λήξει. Ανθεκτικό σε κενά/χαλασμένα strings."""
    if not expires_at_iso:
        return False
    try:
        expires = datetime.fromisoformat(str(expires_at_iso))
    except (TypeError, ValueError):
        return False
    if expires.tzinfo is None:
        expires = expires.replace(tzinfo=timezone.utc)
    return datetime.now(timezone.utc) >= expires


def expires_str_el(expires_at_iso: str) -> str:
    """'21/08/2026' — για τη σελίδα demo και το email. Κενό αν δεν parse-άρει."""
    try:
        return datetime.fromisoformat(str(expires_at_iso)).strftime("%d/%m/%Y")
    except (TypeError, ValueError):
        return ""


